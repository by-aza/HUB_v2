ROOT = Path(__file__).resolve().parents[1]
SQL = ROOT / 'documentatie_tehnica/evidenta_piese/productie'
MIGRATION = ROOT / 'supabase/migrations/20261106122125_ep_release_operations.sql'
COUNT = 0
def check(value, expected, label):
    global COUNT
    assert value == expected, (label, value, expected)
    COUNT += 1
    print('PASS', label, flush=True)

def functions(text):
    return {m.group(1):m.group(0) for m in re.finditer(
        r'CREATE(?: OR REPLACE)? FUNCTION ([\w.]+)\([^;]*?AS (\$\w*\$).*?\2\s*;', text, re.S|re.I)}

def run():
    pg = pgserver.get_server(Path(tempfile.mkdtemp(prefix='hub-ep-release-')), cleanup_mode='stop')
    db = psycopg2.connect(pg.get_uri()); db.autocommit = True
    def query(sql, params=None, conn=db):
        with conn.cursor() as c:
            c.execute(sql, params)
            return c.fetchall() if c.description else []
    try:
        query("""
        CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
        CREATE SCHEMA auth; CREATE SCHEMA private;
        CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
          SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
        CREATE TABLE public.auth_profiles(id uuid PRIMARY KEY,nume text,prenume text,rol_id int,permissions jsonb);
        CREATE TABLE public.auth_roles(id int PRIMARY KEY,numire_rol text);
        INSERT INTO public.auth_roles VALUES(1,'Admin');
        CREATE TABLE public.clienti_vehicule(id bigint PRIMARY KEY,nr_inmatriculare text,serie_vin text);
        CREATE TABLE public.audit_logs(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid,user_name text,
          modul text,actiune text,entitate text,entitate_id text,descriere text);
        CREATE TABLE public.config_alerte(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,cheie text,valoare text);
        CREATE TABLE public.deviz_final_header(id_deviz_final bigint PRIMARY KEY,ep_revision bigint DEFAULT 0);
        CREATE TABLE public.deviz_final_linii(id bigserial PRIMARY KEY,id_deviz_final bigint,sectiune text,nr_crt int,
          cantitate numeric,ep_import_id uuid,ep_alocare_id uuid,ep_snapshot jsonb);
        GRANT USAGE ON SCHEMA auth TO authenticated,anon;
        GRANT SELECT ON public.auth_profiles TO authenticated;
        """)
        base = (SQL/'01_PERSISTENTA_EP.sql').read_text()
        # Eliminăm doar preflight-ul unei instalări istorice deja validate, în DB de test goală.
        base = re.sub(r'DO \$(target|preflight)\$.*?END \$\1\$;', '', base, flags=re.S)
        query(base)
        final = functions((SQL/'03_IMPORT_DF_EP.sql').read_text())
        for name in ['capacity','save_allocations','load_registry']:
            query(final['ep_private.'+name])
        query('ALTER TABLE public.deviz_final_linii ADD CONSTRAINT ep_test_df_source FOREIGN KEY(ep_alocare_id) REFERENCES public.ep_alocari(id) ON DELETE RESTRICT')
        # Triggerul DF real folosește același advisory lock ca operațiile EP.
        query(final['ep_private.df_lock'])
        query('CREATE TRIGGER ep_df_serialize BEFORE INSERT OR UPDATE OR DELETE ON public.deviz_final_linii FOR EACH STATEMENT EXECUTE FUNCTION ep_private.df_lock()')
        # Aplicăm exact candidatul, inclusiv guard-urile de contract și ACL.
        query(MIGRATION.read_text())
        check(query("SELECT has_function_privilege('anon','public.ep_release_quantity(uuid,jsonb)','EXECUTE')")[0][0],False,'anon nu poate executa anulări')
        check(query("SELECT has_table_privilege('authenticated','public.ep_alocari','UPDATE')")[0][0],False,'DML direct rămâne interzis')
        admin,operator,denied = [str(uuid.uuid4()) for _ in range(3)]
        for actor,role,permissions in [(admin,1,{}),(operator,3,{'evidenta_piese':True}),(denied,3,{})]:
            query('INSERT INTO auth_profiles VALUES(%s,%s,%s,%s,%s)',(actor,'Test','Local',role,Json(permissions)))
        query("SELECT set_config('request.jwt.claim.sub',%s,false)",(admin,))
        sid,fid,lid = [str(uuid.uuid4()) for _ in range(3)]
        query("INSERT INTO ep_furnizori(id,denumire,created_by) VALUES(%s,'Furnizor test',%s)",(sid,admin))
        query("INSERT INTO ep_facturi(id,furnizor_id,numar,data_factura,furnizor_denumire_originala,created_by) VALUES(%s,%s,'TEST','2026-11-06','Furnizor test',%s)",(fid,sid,admin))
        query("INSERT INTO ep_factura_linii(id,factura_id,nr_crt,denumire,cantitate,pret_achizitie_net) VALUES(%s,%s,1,'Piesă test',20,10)",(lid,fid))
        def revision(): return query('SELECT revision FROM ep_facturi WHERE id=%s',(fid,))[0][0]
        def capacity(allocation=None): return query('SELECT ep_private.capacity(%s,%s)',(lid,allocation))[0][0]
        def allocate(q,plate='CT44ELD'):
            aid=str(uuid.uuid4())
            query('SELECT public.ep_save_allocations(%s,%s)',(str(uuid.uuid4()),Json({'items':[{'id':aid,'linie_id':lid,'cantitate':q,'nr_inmatriculare':plate,'expected_revision':revision()}]})))
            return aid
        def movement(q,aid=None,kind='magazie'):
            mid=str(uuid.uuid4())
            query('SELECT public.ep_register_movement(%s,%s)',(str(uuid.uuid4()),Json({'id':mid,'kind':kind,'linie_id':lid,'alocare_id':aid,'cantitate':q,'data':'2026-11-06','expected_revision':revision()})))
            return mid
        def release(kind,target,rev=None,request=None,conn=db):
            payload={'id':target,'kind':kind,'expected_revision':revision() if rev is None else rev}
            return query('SELECT public.ep_release_quantity(%s,%s)',(request or str(uuid.uuid4()),Json(payload)),conn)[0][0]
        def blocked(call,label):
            before=(capacity(),revision(),query('SELECT count(*) FROM audit_logs')[0][0])
            try: call()
            except psycopg2.Error: pass
            else: raise AssertionError('Operație acceptată: '+label)
            check((capacity(),revision(),query('SELECT count(*) FROM audit_logs')[0][0]),before,label+' — rollback integral')
        aid=allocate(7); before=capacity(); rev=revision(); req=str(uuid.uuid4())
        result=release('allocation',aid,rev,req)
        check(capacity(),before+7,'resetul eliberează exact alocarea')
        check(query('SELECT cantitate,cantitate_eliberata FROM ep_alocari WHERE id=%s',(aid,))[0],(0,7),'alocarea rămâne arhivată la zero')
        check(query('SELECT count(*) FROM ep_factura_linii WHERE id=%s',(lid,))[0][0],1,'poziția facturii se păstrează')
        check(release('allocation',aid,rev,req),result,'retry identic nu eliberează a doua oară')
        blocked(lambda:query('SELECT public.ep_save_allocations(%s,%s)',(str(uuid.uuid4()),Json({'items':[{'id':aid,'linie_id':lid,'cantitate':1,'nr_inmatriculare':'B400CIR','expected_revision':revision()}]}))),'alocarea arhivată nu poate fi reactivată prin corectare')
        blocked(lambda:release('allocation',aid),'reset repetat cu UUID nou')
        blocked(lambda:release('allocation',aid,revision(),req),'UUID reutilizat cu payload diferit')
        aid=allocate(8); mid=movement(3,aid); other_transfer=movement(1,aid); before=capacity()
        blocked(lambda:release('allocation',aid),'resetul refuză transferul activ')
        query("INSERT INTO deviz_final_linii(id_deviz_final,sectiune,nr_crt,cantitate,ep_import_id,ep_alocare_id,ep_snapshot) VALUES(1,'piese',1,2,gen_random_uuid(),%s,'{}')",(aid,))
        blocked(lambda:release('allocation',aid),'resetul refuză DF salvat')
        release('warehouse',mid)
        check(capacity(),before+3,'anularea transferului alocat revine în De atribuit')
        check(capacity(aid),2,'DF și alt transfer activ rămân acoperite, fără dublă eliberare')
        check(query('SELECT anulat_at FROM ep_transferuri_magazie WHERE id=%s',(other_transfer,))[0][0],None,'alt transfer de pe aceeași alocare rămâne activ')
        check(query('SELECT cantitate FROM deviz_final_linii WHERE ep_alocare_id=%s',(aid,))[0][0],2,'cantitatea DF rămâne identică')
        check(query('SELECT cantitate,anulat_at IS NOT NULL,anulat_de IS NOT NULL FROM ep_transferuri_magazie WHERE id=%s',(mid,))[0],(3,True,True),'transferul păstrează cantitatea, data și actorul anulării')
        blocked(lambda:release('warehouse',mid),'transfer deja anulat')
        aid2=allocate(4,'B400CIR'); mid2=movement(4,aid2); release('warehouse',mid2)
        check(query('SELECT cantitate FROM ep_alocari WHERE id=%s',(aid2,))[0][0],0,'anularea transferului integral arhivează alocarea')
        mid3=movement(2); before=capacity(); release('warehouse',mid3)
        check(capacity(),before+2,'transferul nealocat eliberează numai rezervarea proprie')
        aid3=allocate(2); movement(1,aid3,'retur')
        blocked(lambda:release('allocation',aid3),'resetul refuză returul salvat')
        mid4=movement(1); blocked(lambda:release('warehouse',mid4,revision()-1),'revizie veche')
        query("UPDATE ep_factura_linii SET blocaj_istoric='DF-istoric' WHERE id=%s",(lid,))
        blocked(lambda:release('warehouse',mid4),'istoric DF protejat')
        query('UPDATE ep_factura_linii SET blocaj_istoric=NULL WHERE id=%s',(lid,))
        denied_revision=revision()
        query('SET ROLE authenticated'); query("SELECT set_config('request.jwt.claim.sub',%s,false)",(denied,))
        try:
            query('SELECT public.ep_release_quantity(%s,%s)',(str(uuid.uuid4()),Json({'id':mid4,'kind':'warehouse','expected_revision':denied_revision})))
        except psycopg2.errors.InsufficientPrivilege: check(True,True,'operator fără EP este refuzat')
        else: raise AssertionError('Acces neautorizat')
        query('RESET ROLE'); query("SELECT set_config('request.jwt.claim.sub',%s,false)",(operator,))
        query('SET ROLE authenticated')
        release('warehouse',mid4)
        query('RESET ROLE')
        check(query("SELECT count(*) FROM audit_logs WHERE actiune='release_quantity' AND user_id=%s",(operator,))[0][0],1,'operator cu EP poate anula, audit actor corect')
        query("SELECT set_config('request.jwt.claim.sub',%s,false)",(admin,))
        # Două conexiuni reale: DF deține lock-ul, apoi anularea recitește consumul confirmat.
        aid4=allocate(2); a=psycopg2.connect(pg.get_uri()); b=psycopg2.connect(pg.get_uri()); b.autocommit=True
        query("SELECT set_config('request.jwt.claim.sub',%s,false)",(admin,),b)
        query('SELECT pg_advisory_xact_lock(19520,7001)',conn=a)
        query("INSERT INTO deviz_final_linii(cantitate,ep_alocare_id) VALUES(1,%s)",(aid4,),a)
        outcome=[]; rev=revision()
        def race():
            try: release('allocation',aid4,rev,conn=b);outcome.append('accepted')
            except psycopg2.Error: outcome.append('blocked')
        thread=threading.Thread(target=race); thread.start(); time.sleep(.15)
        check(thread.is_alive(),True,'anularea așteaptă lock-ul DF pe conexiune independentă')
        a.commit(); thread.join(5)
        check(outcome,['blocked'],'după commit DF, resetul recitește și refuză consumul')
        check(capacity(aid4),1,'rasa DF/reset nu dublează disponibilul')
        a.close();b.close()
        reconciled=query('''SELECT ep_private.capacity(%s,NULL)
          + coalesce((SELECT sum(ep_private.capacity(linie_id,id)) FROM ep_alocari WHERE linie_id=%s),0)
          + coalesce((SELECT sum(cantitate) FROM ep_retururi WHERE linie_id=%s),0)
          + coalesce((SELECT sum(cantitate) FROM ep_transferuri_magazie WHERE linie_id=%s AND anulat_at IS NULL),0)
          + coalesce((SELECT sum(d.cantitate) FROM deviz_final_linii d JOIN ep_alocari a ON a.id=d.ep_alocare_id WHERE a.linie_id=%s),0)''',(lid,)*5)[0][0]
        check(reconciled,20,'De atribuit + alocat liber + retur + magazie activă + DF = cantitatea facturii')
        check(query("SELECT bool_and((descriere::jsonb ? 'before') AND (descriere::jsonb ? 'after')) FROM audit_logs WHERE actiune='release_quantity'")[0][0],True,'auditul păstrează starea before/after')
        test_deletion(query,db,pg,sid,admin,operator,denied)
        print(f'TOTAL {COUNT} PASS — PostgreSQL local {query("SHOW server_version")[0][0]}',flush=True)
    finally:
        db.close();pg.cleanup()

def test_deletion(query,db,pg,sid,admin,operator,denied):
    """Facturi sintetice distincte pentru ștergeri, FK, retry și concurență."""
    def rev(fid): return query('SELECT revision FROM ep_facturi WHERE id=%s',(fid,))[0][0]
    def make_invoice():
        fid=str(uuid.uuid4()); lines=[str(uuid.uuid4()),str(uuid.uuid4())]
        query("INSERT INTO ep_facturi(id,furnizor_id,numar,data_factura,furnizor_denumire_originala,created_by) VALUES(%s,%s,%s,'2026-11-06','Furnizor test',%s)",(fid,sid,'TEST-'+fid.upper(),admin))
        for n,lid in enumerate(lines,1):
            query('INSERT INTO ep_factura_linii(id,factura_id,nr_crt,denumire,cantitate,pret_achizitie_net) VALUES(%s,%s,%s,%s,10,10)',(lid,fid,n,'Poziția '+str(n)))
        return fid,lines
    def allocation(fid,lid,q=2,conn=db):
        aid=str(uuid.uuid4()); payload={'items':[{'id':aid,'linie_id':lid,'cantitate':q,'nr_inmatriculare':'CT44ELD','expected_revision':rev(fid)}]}
        query('SELECT public.ep_save_allocations(%s,%s)',(str(uuid.uuid4()),Json(payload)),conn); return aid
    def movement(fid,lid,aid=None,kind='magazie'):
        mid=str(uuid.uuid4()); payload={'id':mid,'kind':kind,'linie_id':lid,'alocare_id':aid,'cantitate':2,'data':'2026-11-06','expected_revision':rev(fid)}
        query('SELECT public.ep_register_movement(%s,%s)',(str(uuid.uuid4()),Json(payload))); return mid
    def release(fid,kind,target):
        query('SELECT public.ep_release_quantity(%s,%s)',(str(uuid.uuid4()),Json({'kind':kind,'id':target,'expected_revision':rev(fid)})))
    def save_lines(fid,keep,request=None,expected=None):
        payload={'id':fid,'furnizor_id':sid,'numar':'TEST-'+fid.upper(),'data_factura':'2026-11-06','expected_revision':rev(fid) if expected is None else expected,
            'lines':[{'id':lid,'denumire':'Poziție editată','cantitate':10,'pret_achizitie_net':'10','tva_proc':21,'coeficient_df':'1.53','nr_inmatriculare':''} for lid in keep]}
        return query('SELECT public.ep_save_invoice(%s,%s)',(request or str(uuid.uuid4()),Json(payload)))[0][0]
    def delete(fid,request=None,expected=None,conn=db):
        return query('SELECT public.ep_delete_invoice(%s,%s)',(request or str(uuid.uuid4()),Json({'id':fid,'expected_revision':rev(fid) if expected is None else expected})),conn)[0][0]
    def state(fid):
        return query('''SELECT jsonb_build_object('invoice',(SELECT to_jsonb(f) FROM ep_facturi f WHERE id=%s),
          'lines',(SELECT jsonb_agg(to_jsonb(l) ORDER BY id) FROM ep_factura_linii l WHERE factura_id=%s),
          'allocations',(SELECT jsonb_agg(to_jsonb(a) ORDER BY a.id) FROM ep_alocari a JOIN ep_factura_linii l ON l.id=a.linie_id WHERE l.factura_id=%s),
          'transfers',(SELECT jsonb_agg(to_jsonb(t) ORDER BY t.id) FROM ep_transferuri_magazie t JOIN ep_factura_linii l ON l.id=t.linie_id WHERE l.factura_id=%s),
          'returns',(SELECT jsonb_agg(to_jsonb(t) ORDER BY t.id) FROM ep_retururi t JOIN ep_factura_linii l ON l.id=t.linie_id WHERE l.factura_id=%s),
          'df',(SELECT jsonb_agg(to_jsonb(d) ORDER BY d.id) FROM deviz_final_linii d JOIN ep_alocari a ON a.id=d.ep_alocare_id JOIN ep_factura_linii l ON l.id=a.linie_id WHERE l.factura_id=%s),
          'audit_count',(SELECT count(*) FROM audit_logs))''',(fid,)*6)[0][0]
    def blocked(fid,call,word,label):
        before=state(fid)
        try: call()
        except psycopg2.Error as error:
            check(word in str(error),True,label+' — motiv românesc')
        else: raise AssertionError('Ștergere acceptată: '+label)
        check(state(fid),before,label+' — fără ștergere, resetare sau anulare parțială')
    check(query("SELECT has_function_privilege('anon','public.ep_delete_invoice(uuid,jsonb)','EXECUTE')")[0][0],False,'ștergerea facturii refuză anon')
    check(query("SELECT has_function_privilege('authenticated','ep_private.remove_unused_line(uuid)','EXECUTE')")[0][0],False,'helperul distructiv nu este apelabil de operator')
    check(query("SELECT has_table_privilege('authenticated','public.ep_facturi','DELETE')")[0][0],False,'nu se acordă DELETE direct pe facturi')
    fid,lines=make_invoice(); aid=allocation(fid,lines[1]); release(fid,'allocation',aid)
    req=str(uuid.uuid4()); old_revision=rev(fid); result=save_lines(fid,[lines[0]],req,old_revision)
    check(query('SELECT count(*) FROM ep_factura_linii WHERE factura_id=%s',(fid,))[0][0],1,'reset atribuire → eliminare linie → salvare reușită')
    archive=query('SELECT descriere::jsonb FROM audit_logs WHERE id=%s',(req,))[0][0]['before']['removed_lines'][0]
    check((archive['allocations'][0]['id'],archive['allocations'][0]['cantitate_eliberata']),(aid,2),'istoricul alocării eliminate rămâne în audit')
    check(save_lines(fid,[lines[0]],req,old_revision),result,'retry la salvarea eliminării este idempotent')
    fid,lines=make_invoice(); aid=allocation(fid,lines[1]); mid=movement(fid,lines[1],aid); release(fid,'warehouse',mid)
    req=str(uuid.uuid4());save_lines(fid,[lines[0]],req)
    archive=query('SELECT descriere::jsonb FROM audit_logs WHERE id=%s',(req,))[0][0]['before']['removed_lines'][0]
    check(query('SELECT count(*) FROM ep_factura_linii WHERE id=%s',(lines[1],))[0][0],0,'anulare trimitere din alocare → eliminare linie fără eroare FK')
    check((archive['transfers'][0]['id'],bool(archive['transfers'][0]['anulat_at'])),(mid,True),'trimiterea anulată eliminată rămâne în audit')
    fid,lines=make_invoice();mid=movement(fid,lines[1]);release(fid,'warehouse',mid);save_lines(fid,[lines[0]])
    check(query('SELECT count(*) FROM ep_factura_linii WHERE id=%s',(lines[1],))[0][0],0,'anulare trimitere nealocată → eliminare linie reușită')
    fid,lines=make_invoice(); req=str(uuid.uuid4()); expected=rev(fid); result=delete(fid,req,expected)
    check((result['deleted'],result['deleted_lines']),(True,2),'ștergere factură complet nefolosită')
    check(query('SELECT count(*) FROM ep_facturi WHERE id=%s',(fid,))[0][0],0,'antetul facturii este eliminat')
    check(query('SELECT count(*) FROM ep_factura_linii WHERE factura_id=%s',(fid,))[0][0],0,'toate liniile facturii sunt eliminate')
    count=query('SELECT count(*) FROM audit_logs')[0][0]
    check(delete(fid,req,expected),result,'retry după ștergere întoarce rezultatul inițial')
    check(query('SELECT count(*) FROM audit_logs')[0][0],count,'retry nu dublează auditul ștergerii')
    audit=query('SELECT descriere::jsonb FROM audit_logs WHERE id=%s',(req,))[0][0]
    check((audit['before']['invoice']['id'],len(audit['before']['removed_lines'])),(fid,2),'auditul ștergerii păstrează strict factura și liniile ei')
    for kind,word in [('allocation','atribuire auto activă'),('warehouse','trimitere activă'),('df','DF salvat'),('return','retur înregistrat'),('legacy','istoric financiar protejat')]:
        fid,lines=make_invoice()
        if kind=='allocation':allocation(fid,lines[1])
        elif kind=='warehouse':movement(fid,lines[1])
        elif kind=='df':
            aid=allocation(fid,lines[1]);query("INSERT INTO deviz_final_linii(cantitate,ep_import_id,ep_alocare_id,ep_snapshot) VALUES(1,gen_random_uuid(),%s,'{}')",(aid,))
        elif kind=='return':movement(fid,lines[1],kind='retur')
        else:query("UPDATE ep_factura_linii SET blocaj_istoric='DF-istoric' WHERE id=%s",(lines[1],))
        blocked(fid,lambda:delete(fid),word,'factură blocată '+kind)
        blocked(fid,lambda:save_lines(fid,[lines[0]]),word,'eliminare linie blocată '+kind)
    fid,lines=make_invoice();aid=allocation(fid,lines[1]);release(fid,'allocation',aid);mid=movement(fid,lines[1]);release(fid,'warehouse',mid)
    req=str(uuid.uuid4());delete(fid,req)
    archived=query('SELECT descriere::jsonb FROM audit_logs WHERE id=%s',(req,))[0][0]['before']['removed_lines'][1]
    check((archived['allocations'][0]['id'],archived['transfers'][0]['id']),(aid,mid),'factură cu reset/anulare manuală se șterge cu istoric arhivat')
    # O dependență necunoscută/FK pe ultima poziție trebuie să refacă și prima poziție deja eliminată.
    query('CREATE TABLE ep_test_protected(line_id uuid REFERENCES ep_factura_linii(id) ON DELETE RESTRICT)')
    fid,lines=make_invoice();aid=allocation(fid,lines[0]);release(fid,'allocation',aid)
    query('INSERT INTO ep_test_protected VALUES(%s)',(lines[1],))
    blocked(fid,lambda:delete(fid),'alte dependențe protejate','FK suplimentar pe ultima linie')
    fid,lines=make_invoice();blocked(fid,lambda:delete(fid,expected=rev(fid)-1),'Factura a fost modificată','revizie veche la ștergere')
    expected=rev(fid);query('SET ROLE authenticated');query("SELECT set_config('request.jwt.claim.sub',%s,false)",(denied,))
    try: delete(fid,expected=expected)
    except psycopg2.errors.InsufficientPrivilege: check(True,True,'ștergerea refuză operator fără EP')
    else: raise AssertionError('Ștergere neautorizată')
    query("SELECT set_config('request.jwt.claim.sub',%s,false)",(operator,));req=str(uuid.uuid4());delete(fid,req,expected)
    query('RESET ROLE')
    check(query('SELECT user_id::text FROM audit_logs WHERE id=%s',(req,))[0][0],operator,'operator EP autorizat: actorul auditului vine din sesiune')
    query("SELECT set_config('request.jwt.claim.sub',%s,false)",(admin,))
    # Audit imposibil => nici factura nu trebuie să dispară.
    query("CREATE FUNCTION ep_test_audit_fail() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.actiune='delete_invoice' THEN RAISE EXCEPTION 'audit indisponibil'; END IF; RETURN NEW; END $$")
    query('CREATE TRIGGER ep_test_audit_fail BEFORE INSERT ON audit_logs FOR EACH ROW EXECUTE FUNCTION ep_test_audit_fail()')
    fid,lines=make_invoice();blocked(fid,lambda:delete(fid),'audit indisponibil','eșec audit')
    query('DROP TRIGGER ep_test_audit_fail ON audit_logs')
